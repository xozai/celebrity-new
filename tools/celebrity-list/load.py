"""
Load celebrity recommendations CSV into PostgreSQL / Supabase database.
Upserts records by name_norm, and deletes rows no longer present in the list.
Supports atomic transactions and minimum row-count guard.
Python 3 standard library only.
"""

from __future__ import annotations

import argparse
import csv
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any, Callable

DEFAULT_CSV_PATH = Path(__file__).resolve().parent / "celebrities.csv"
MIN_ROWS_DEFAULT = 2000


def parse_sources_column(val: str) -> list[str]:
    """Parse Postgres text array string, e.g. '{imdb,wikipedia}' or 'imdb,wikipedia'."""
    val = val.strip()
    if val.startswith("{") and val.endswith("}"):
        val = val[1:-1]
    items = [s.strip().replace('"', "") for s in val.split(",") if s.strip()]
    return items


def parse_celebrities_csv(csv_path: str | Path) -> list[dict[str, Any]]:
    """Parse celebrities.csv into validated dictionaries."""
    rows: list[dict[str, Any]] = []
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for r in reader:
            name = (r.get("name") or "").strip()
            name_norm = (r.get("name_norm") or "").strip()
            if not name or not name_norm:
                continue
            desc = (r.get("description") or "").strip()
            category = (r.get("category") or "other").strip()
            pop = float(r.get("popularity", 0.0))
            sources = parse_sources_column(r.get("sources", ""))
            rows.append(
                {
                    "name": name,
                    "name_norm": name_norm,
                    "description": desc,
                    "category": category,
                    "popularity": pop,
                    "sources": sources,
                }
            )
    return rows


def sql_quote(val: str) -> str:
    """Escape and quote string literal for SQL."""
    return "'" + val.replace("'", "''") + "'"


def generate_load_sql(rows: list[dict[str, Any]], batch_size: int = 500) -> str:
    """
    Generate atomic SQL script to upsert rows into celebrities table
    and delete rows no longer in the list.
    """
    lines: list[str] = [
        "-- Celebrity list upsert generated by load.py",
        "BEGIN;",
        "",
        "-- Create temporary staging table with identical columns",
        "CREATE TEMP TABLE staging_celebrities (",
        "  name text NOT NULL,",
        "  name_norm text NOT NULL,",
        "  description text,",
        "  category text,",
        "  popularity real NOT NULL,",
        "  sources text[] NOT NULL",
        ") ON COMMIT DROP;",
        "",
    ]

    # Insert rows into staging_celebrities in batches
    for i in range(0, len(rows), batch_size):
        batch = rows[i : i + batch_size]
        values_clauses = []
        for r in batch:
            name_lit = sql_quote(r["name"])
            norm_lit = sql_quote(r["name_norm"])
            desc_lit = sql_quote(r.get("description", ""))
            cat_lit = sql_quote(r.get("category", "other"))
            pop_lit = f"{float(r.get('popularity', 0.0)):.4f}"

            # Format Postgres array literal: ARRAY['source1', 'source2']::text[]
            src_lits = ", ".join(sql_quote(s) for s in r.get("sources", []))
            sources_lit = f"ARRAY[{src_lits}]::text[]"

            values_clauses.append(
                f"  ({name_lit}, {norm_lit}, {desc_lit}, {cat_lit}, {pop_lit}, {sources_lit})"
            )

        lines.append(
            "INSERT INTO staging_celebrities (name, name_norm, description, category, popularity, sources) VALUES"
        )
        lines.append(",\n".join(values_clauses) + ";\n")

    # Upsert into target table
    lines.extend(
        [
            "-- Upsert from staging into celebrities",
            "INSERT INTO celebrities (name, name_norm, description, category, popularity, sources)",
            "SELECT name, name_norm, description, category, popularity, sources",
            "FROM staging_celebrities",
            "ON CONFLICT (name_norm) DO UPDATE SET",
            "  name = EXCLUDED.name,",
            "  description = EXCLUDED.description,",
            "  category = EXCLUDED.category,",
            "  popularity = EXCLUDED.popularity,",
            "  sources = EXCLUDED.sources;",
            "",
            "-- Delete celebrities no longer present in the updated list",
            "DELETE FROM celebrities",
            "WHERE name_norm NOT IN (SELECT name_norm FROM staging_celebrities);",
            "",
            "COMMIT;",
        ]
    )

    return "\n".join(lines)


def execute_load(
    database_url: str | None = None,
    rows: list[dict[str, Any]] | None = None,
    csv_path: str | Path | None = None,
    min_rows: int = MIN_ROWS_DEFAULT,
    executor: Callable[[str], None] | None = None,
) -> None:
    """Execute SQL loading against database."""
    if rows is None:
        if csv_path is None:
            csv_path = DEFAULT_CSV_PATH
        rows = parse_celebrities_csv(csv_path)

    if len(rows) < min_rows:
        raise ValueError(
            f"Row count {len(rows)} is below safety threshold of {min_rows}. "
            "Aborting database load."
        )

    sql = generate_load_sql(rows)

    if executor is not None:
        executor(sql)
        return

    if not database_url:
        raise ValueError("DATABASE_URL must be provided to load into database.")

    psql_bin = shutil.which("psql")
    if not psql_bin:
        raise RuntimeError(
            "psql command line tool not found on PATH. "
            "Please install postgresql client tools to execute against DATABASE_URL."
        )

    proc = subprocess.run(
        [psql_bin, database_url, "-v", "ON_ERROR_STOP=1"],
        input=sql.encode("utf-8"),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )
    print("Database load completed successfully.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Load celebrities.csv into database.")
    parser.add_argument(
        "csv_file",
        nargs="?",
        type=Path,
        default=DEFAULT_CSV_PATH,
        help="Path to celebrities.csv",
    )
    parser.add_argument(
        "--database-url",
        type=str,
        default=os.environ.get("DATABASE_URL") or os.environ.get("PRODUCTION_DATABASE_URL"),
        help="Database connection URL",
    )
    parser.add_argument(
        "--min-rows",
        type=int,
        default=MIN_ROWS_DEFAULT,
        help=f"Minimum rows required to proceed with load (default: {MIN_ROWS_DEFAULT})",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Generate and validate SQL without executing against database",
    )
    args = parser.parse_args()

    if not args.csv_file.exists():
        print(f"Error: CSV file not found: {args.csv_file}", file=sys.stderr)
        sys.exit(1)

    print(f"Parsing {args.csv_file}...")
    rows = parse_celebrities_csv(args.csv_file)
    print(f"Parsed {len(rows)} celebrity records.")

    if args.dry_run:
        print("[DRY RUN] Validating SQL generation...")
        sql = generate_load_sql(rows)
        print(f"[DRY RUN] Generated SQL script of {len(sql)} characters.")
        print("[DRY RUN] Preview:")
        print("\n".join(sql.splitlines()[:25]))
        print("...")
        print("[DRY RUN] Finished without executing.")
        return

    try:
        execute_load(
            database_url=args.database_url,
            rows=rows,
            min_rows=args.min_rows,
        )
    except Exception as e:
        print(f"Error executing load: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
